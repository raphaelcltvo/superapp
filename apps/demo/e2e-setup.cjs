// Setup de uma marca nova na demonstração: criar conta → 9 passos → cardápio no ar.
const { chromium } = require("playwright");
const OUT = process.env.OUT || ".";
(async () => {
  const b = await chromium.launch({ proxy: { server: process.env.HTTPS_PROXY, bypass: "<-loopback>,localhost,127.0.0.1" }, args: ["--ignore-certificate-errors"] });
  const pg = await b.newPage({ viewport: { width: 1500, height: 940 }, ignoreHTTPSErrors: true });
  const errs = []; pg.on("pageerror", (e) => errs.push(e.message)); pg.on("console", (m) => { if (m.type() === "error" && !/Failed to load resource|404|422/.test(m.text())) errs.push(m.text()); });
  const ok = (c, m) => console.log((c ? "ok: " : "FALHOU: ") + m);
  const shot = (n) => pg.screenshot({ path: `${OUT}/${n}.png` });
  await pg.goto("http://localhost:" + (process.env.PORT || 8811) + "/index.html");
  await pg.waitForSelector(".cw-sf .store-name", { timeout: 60000 });
  await pg.click("#demo-new-brand");
  await pg.waitForSelector("#su-brand", { timeout: 60000 });
  await pg.fill("#su-brand", "Brasa do Sul"); await pg.fill("#su-owner", "Rafa"); await pg.fill("#login-email", "rafa@brasadosul.com"); await pg.fill("#login-pw", "brasa2026!");
  await shot("s0-criar"); await pg.click('button:has-text("Criar e começar o Setup")');
  await pg.waitForSelector("#su-name", { timeout: 15000 });
  ok(/Passo 1 de 9/.test(await pg.locator(".su-body").textContent()), "Setup abre no passo 1 (Marca)");
  await pg.fill("#su-wa", "(21) 98888-7777");
  await pg.click('.su-sw button[aria-label="#3E2723"]');
  await shot("s1-marca"); await pg.click("#su-brand-save");
  await pg.waitForSelector('.su-cu[data-cuisine="churrasco"]', { timeout: 8000 });
  await pg.click('.su-cu[data-cuisine="churrasco"]');
  ok(/Venda por peso/.test(await pg.locator(".su-tips").textContent()), "culinária explica as particularidades (venda por peso)");
  await shot("s2-culinaria"); await pg.click("#su-cuisine-save");
  await pg.waitForSelector("#su-store", { timeout: 8000 });
  await pg.fill("#su-store", "Brasa do Sul · Recreio"); await pg.fill("#su-cep", "22790-000"); await pg.fill("#su-street", "Av. das Américas"); await pg.fill("#su-number", "15000"); await pg.fill("#su-district", "Recreio"); await pg.fill("#su-city", "Rio de Janeiro");
  await shot("s3-loja"); await pg.click("#su-store-save");
  await pg.waitForSelector('[data-src="modelo"]', { timeout: 8000 });
  await pg.click('[data-src="modelo"]');
  await pg.waitForSelector("#su-tpl-apply");
  ok(/Costela no bafo/.test(await pg.locator(".su-tpl").textContent()), "modelo de churrasco mostra itens de exemplo");
  await shot("s4-cardapio"); await pg.click("#su-tpl-apply");
  await pg.waitForSelector(".su-have:has-text('itens')", { timeout: 8000 });
  ok(/\d+ itens/.test(await pg.locator(".su-have").first().textContent()), "cardápio criado no rascunho");
  await pg.click('.su-have button:has-text("Continuar")');
  await pg.waitForSelector("#su-pay-save", { timeout: 8000 });
  await shot("s5-pagamento"); await pg.click("#su-pay-save");
  await pg.waitForSelector("#su-orders-save", { timeout: 8000 });
  await shot("s6-pedidos"); await pg.click("#su-orders-save");
  await pg.waitForSelector(".su-body .wa-connect", { timeout: 8000 });
  await pg.locator(".su-body #wa-qr").click();
  await pg.locator('.su-body img[alt^="QR code"]').waitFor({ timeout: 8000 });
  await shot("s7-whatsapp");
  await pg.locator('.su-body button:has-text("Simular leitura")').click();
  await pg.waitForFunction(() => /conectado ·/.test(document.querySelector(".su-body .wa-connect")?.textContent || ""), null, { timeout: 8000 });
  await pg.waitForTimeout(600);
  ok(await pg.locator('.su-step:has-text("WhatsApp") .su-n.ok').count() === 1, "WhatsApp conectado por QR marca o passo como pronto");
  await shot("s7b-whatsapp-ok");
  await pg.locator('.su-step:has(b:text-is("Publicar"))').evaluate((el) => el.click());
  await pg.waitForSelector("#su-publish", { timeout: 8000 });
  await pg.click("#su-publish");
  await pg.waitForSelector(".su-live", { timeout: 8000 });
  await shot("s9-publicado");
  ok(/brasa-do-sul/.test(await pg.locator(".su-live .codebox").textContent()), "link do cardápio da marca nova");
  const sf = pg.locator(".demo-screen");
  await sf.locator(".card:has-text('Costela no bafo')").waitFor({ timeout: 15000 });
  const card = await sf.locator(".card:has-text('Costela no bafo')").textContent();
  ok(/139,80\/kg/.test(card), "cardápio do cliente mostra preço por kg: " + card.replace(/\s+/g, " ").slice(0, 90));
  try { await sf.locator(".fv-sheet button:has-text('Pular'), .fv-sheet button:has-text('Agora não')").first().click({ timeout: 3000 }); } catch { /* sem triagem */ }
  await sf.locator(".card:has-text('Costela no bafo') .tap").click();
  await sf.locator(".grp:has-text('2 grátis')").first().waitFor({ timeout: 5000 }).catch(() => {});
  ok(/grátis/.test(await sf.locator(".sheet").textContent()), "acompanhamentos com cota grátis no item");
  await shot("s10-item");
  // encomenda: junta o modelo de confeitaria, publica e agenda uma torta com a loja fechada
  await sf.locator(".sheet .x").click().catch(() => {});
  await pg.locator('.su-step:has(b:text-is("Cardápio"))').evaluate((el) => el.click()); await pg.waitForTimeout(400);
  await pg.click('[data-src="modelo"]');
  await pg.selectOption('select[aria-label="Modelo de culinária"]', "confeitaria");
  await pg.click('button:has-text("Juntar ao que já existe")'); await pg.waitForTimeout(800);
  await pg.click("#btn-publish"); await pg.waitForTimeout(1500);
  await sf.locator(".card:has-text('Torta de limão inteira')").waitFor({ timeout: 15000 });
  ok(/Encomenda 1d/.test(await sf.locator(".card:has-text('Torta de limão inteira')").textContent()), "item de encomenda mostra o selo de antecedência");
  await sf.locator(".card:has-text('Torta de limão inteira') .qadd").click(); await pg.waitForTimeout(500);
  await sf.locator(".bagbar").click(); await pg.waitForTimeout(500);
  await sf.locator('[data-screen="bag"] .foot-cta .cta').click(); await pg.waitForTimeout(500);
  await sf.locator('button[role="radio"]:has-text("Retirar na loja")').click().catch(() => {});
  await sf.locator(".sched").waitFor({ timeout: 5000 });
  const ctaTxt = await sf.locator('[data-screen="checkout"] .foot-cta .cta').textContent(); ok(/Fechado agora|Escolha a data/.test(ctaTxt), "sem data a encomenda não segue: " + ctaTxt);
  await sf.locator('.sched button:has-text("Primeiro horário")').click();
  await sf.locator('.payopt:has-text("Crédito")').first().click();
  await sf.locator("#cw-name").fill("Encomenda Teste"); await sf.locator("#cw-phone").fill("21 9" + String(Date.now()).slice(-8));
  await sf.locator('button:has-text("Receber código")').click(); await sf.locator("#cw-code").fill("1234"); await sf.locator('button:has-text("Confirmar código")').click();
  await sf.locator(".ident-ok").waitFor(); await pg.waitForTimeout(600);
  await shot("s11-encomenda");
  await sf.locator('[data-screen="checkout"] .foot-cta .cta').click(); await pg.waitForTimeout(1500);
  await pg.click('.cw-ad .navbtn:has-text("Pedidos")');
  const ag = pg.locator(".cw-ad .kb-col:has-text('Agendados') .kb-card").first();
  await ag.waitFor({ timeout: 10000 });
  ok(/Torta de limão/.test(await ag.textContent()), "encomenda feita com a loja fechada cai em Agendados no gestor");
  await shot("s12-agendados");
  ok(!errs.length, errs.length ? "erros: " + errs.slice(0, 3).join(" | ") : "sem erros no console");
  await b.close();
})();
