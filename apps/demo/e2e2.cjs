const { chromium } = require("playwright");
const OUT = process.env.OUT || ".";
(async () => {
  const b = await chromium.launch({ proxy: { server: process.env.HTTPS_PROXY, bypass: "<-loopback>,localhost,127.0.0.1" }, args: ["--ignore-certificate-errors"] });
  const pg = await b.newPage({ viewport: { width: 1500, height: 920 }, ignoreHTTPSErrors: true });
  const errs = []; pg.on("pageerror", (e) => errs.push(e.message)); pg.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
  const ok = (c, m) => console.log((c ? "ok: " : "FALHOU: ") + m);
  await pg.goto("http://localhost:8811/index.html");
  await pg.waitForSelector(".cw-sf .store-name", { timeout: 60000 });
  const sf = pg.locator(".demo-screen");
  await sf.locator('[data-id="s40"] .info').click();
  await sf.locator('#g-g_sab40 .opt-row:has-text("4 Queijos") button[aria-label^="Adicionar"]').first().click();
  await sf.locator('#g-g_sab40 .opt-row:has(.o-n:text-is("Marguerita")) button[aria-label^="Adicionar"]').click();
  ok(/131,50/.test(await sf.locator("#cta-add").textContent()), "preço meio a meio no cardápio da demo");
  await sf.locator("#cta-add").click(); await pg.waitForTimeout(600);
  await sf.locator(".bagbar").click(); await pg.waitForTimeout(600);
  await sf.locator('[data-screen="bag"] .foot-cta .cta').click(); await pg.waitForTimeout(400);
  await sf.locator("#cw-a-postalCode").fill("22431-050"); await sf.locator("#cw-a-number").fill("100"); await sf.locator("#cw-a-street").fill("Rua Dias Ferreira"); await sf.locator("#cw-a-district").fill("Leblon"); await sf.locator("#cw-a-city").click();
  await sf.locator('[data-screen="checkout"] .okline').waitFor();
  await sf.locator('.payopt:has-text("Pix")').click();
  await sf.locator("#cw-name").fill("Raphael Teste"); await sf.locator("#cw-phone").fill("21 9" + String(Date.now()).slice(-8));
  await sf.locator('button:has-text("Receber código")').click(); await sf.locator("#cw-code").fill("1234"); await sf.locator('button:has-text("Confirmar código")').click();
  await sf.locator(".ident-ok").waitFor(); await pg.waitForTimeout(500);
  await sf.locator('[data-screen="checkout"] .foot-cta .cta').click();
  await pg.waitForTimeout(2500);
  await pg.screenshot({ path: OUT + "/7-pix.png" });
  // Pix simulado → acompanhamento
  const pay = sf.locator('button:has-text("Já paguem"), button:has-text("Já paguei"), button:has-text("Simular pagamento")');
  if (await pay.count()) await pay.first().click();
  await pg.waitForTimeout(27000);
  await pg.screenshot({ path: OUT + "/8-track.png" });
  ok(/Entregue|entregue/.test(await sf.textContent()), "status chegou a entregue pelo webhook da SAIPOS de teste");
  await pg.click('.cw-ad .navbtn:has-text("Pedidos")'); await pg.waitForTimeout(1200);
  const row = await pg.locator(".cw-ad table tbody tr").first().textContent();
  ok(/Entregue/.test(row), "pedido aparece no painel como Entregue: " + row.replace(/\s+/g, " ").slice(0, 90));
  await pg.locator(".cw-ad table tbody tr").first().click(); await pg.waitForTimeout(800);
  await pg.screenshot({ path: OUT + "/9-pedido.png" });
  await pg.keyboard.press("Escape");
  await pg.click('#btn-publish'); await pg.waitForTimeout(1200);
  ok(/versão 2/.test(await pg.locator(".cw-ad .topbar").textContent()), "publicou versão 2");
  console.log(errs.length ? errs.slice(0, 10) : "sem erros");
  await b.close();
})();
