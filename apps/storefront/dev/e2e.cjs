// Jornada completa no cardápio: abertura, busca, meio a meio, sacola, revisão, OTP, pedido e acompanhamento.
const { chromium } = require("playwright");
const OUT = process.env.OUT || ".";
const URL = process.env.SF_URL || "http://127.0.0.1:5197/?api=http://localhost:8797&utm_source=instagram&idle=4";
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 820 }, deviceScaleFactor: 2 });
  const pg = await ctx.newPage();
  const errs = [];
  pg.on("pageerror", (e) => errs.push("pageerror: " + e.message));
  pg.on("console", (m) => { if (m.type() === "error" && !/fonts\.g/.test(m.text())) errs.push("console: " + m.text()); });
  const ok = (c, msg) => { if (!c) { console.log("FALHOU:", msg); process.exitCode = 1; } else console.log("ok:", msg); };
  await pg.goto(URL);
  await pg.waitForSelector(".store-name");
  await pg.waitForTimeout(800);
  await pg.screenshot({ path: OUT + "/sf1-menu.png" });
  ok(await pg.isVisible(".lupa-cover"), "lupa no topo");
  ok(!(await pg.isVisible(".search")), "sem barra de busca no corpo");
  ok(await pg.isVisible(".slot-top .banner video, .slot-top .banner img"), "banner do topo");
  ok(await pg.isVisible("#t-hero"), "card sugerido");
  // pop-up de cupom (idle=4s, cliente novo)
  await pg.waitForSelector(".popup.pos-top-right", { timeout: 9000 });
  ok(/BEMVINDO10/.test(await pg.textContent(".popup")), "pop-up com cupom no canto superior direito");
  await pg.screenshot({ path: OUT + "/sf2-popup.png" });
  await pg.click(".popup .btn-brand");
  // busca
  await pg.click(".lupa-cover");
  await pg.fill("#cw-search", "catupiry");
  await pg.waitForSelector(".sres");
  ok((await pg.$$(".sres")).length > 0, "busca por sabor encontra itens");
  await pg.click(".search-hd .back");
  // meio a meio
  await pg.click('[data-id="s40"] .info');
  await pg.waitForSelector(".sheet.on");
  ok(/Falta/.test(await pg.textContent("#cta-add")), "CTA mostra o que falta");
  await pg.click('#g-g_sab40 .opt-row:has-text("4 Queijos") button[aria-label^="Adicionar"] >> nth=0');
  await pg.click('#g-g_sab40 .opt-row:has(.o-n:text-is("Marguerita")) button[aria-label^="Adicionar"]');
  const cta = await pg.textContent("#cta-add");
  ok(/131,50/.test(cta), "1/2 4 Queijos + 1/2 Marguerita = R$ 131,50 (" + cta.replace(/\s+/g, " ") + ")");
  ok(await pg.isVisible(".item-ph .ph-box.half"), "foto meio a meio montada");
  await pg.evaluate(() => document.querySelector(".sheet-scroll").scrollTo(0, 0));
  await pg.waitForTimeout(400);
  await pg.screenshot({ path: OUT + "/sf3-item.png" });
  await pg.click("#cta-add");
  await pg.waitForTimeout(700);
  await pg.click(".bagbar");
  await pg.waitForSelector('[data-screen="bag"] .line');
  await pg.waitForTimeout(900);
  ok(await pg.isVisible('[data-screen="bag"] .prog') || await pg.isVisible('[data-screen="bag"] .benefit'), "barra de frete grátis ou benefício na sacola");
  ok(!/m[ií]nimo/i.test(await pg.textContent('[data-screen="bag"]')), "sacola não fala de pedido mínimo");
  await pg.screenshot({ path: OUT + "/sf4-bag.png" });
  await pg.click('[data-screen="bag"] .foot-cta .cta');
  await pg.waitForTimeout(500);
  await pg.fill("#cw-a-postalCode", "22431-050");
  await pg.fill("#cw-a-number", "100");
  await pg.fill("#cw-a-street", "Rua Dias Ferreira");
  await pg.fill("#cw-a-district", "Leblon");
  await pg.click("#cw-a-city");
  await pg.waitForSelector('[data-screen="checkout"] .okline');
  await pg.click('.payopt:has-text("Dinheiro")');
  await pg.fill("#cw-change", "200");
  await pg.fill("#cw-name", "Cliente Teste");
  await pg.fill("#cw-phone", "21 9" + String(Date.now()).slice(-8));
  await pg.click('button:has-text("Receber código")');
  await pg.waitForSelector("#cw-code");
  await pg.fill("#cw-code", "1234");
  await pg.click('button:has-text("Confirmar código")');
  await pg.waitForSelector(".ident-ok");
  await pg.waitForTimeout(800);
  const sum = await pg.textContent('[data-screen="checkout"]');
  ok(/BEMVINDO10/.test(await pg.inputValue("#cw-coupon")), "cupom do pop-up preenchido na revisão");
  await pg.screenshot({ path: OUT + "/sf5-checkout.png", fullPage: false });
  await pg.click('[data-screen="checkout"] .foot-cta .cta');
  await pg.waitForSelector('[data-screen="track"] .timeline', { timeout: 8000 });
  await pg.waitForTimeout(1500);
  const tr = await pg.textContent('[data-screen="track"]');
  ok(/Enviado para a cozinha|Pedido recebido/.test(tr), "acompanhamento com linha do tempo");
  await pg.screenshot({ path: OUT + "/sf6-track.png" });
  const w = await pg.evaluate(() => document.querySelector(".cw-sf").scrollWidth <= document.querySelector(".cw-sf").clientWidth);
  ok(w, "sem rolagem lateral");
  console.log("resumo revisão:", sum.replace(/\s+/g, " ").slice(-260));
  console.log(errs.length ? errs : "sem erros no console");
  await b.close();
})();
